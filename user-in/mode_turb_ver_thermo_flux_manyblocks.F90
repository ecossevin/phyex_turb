  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI, JK) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

    DO JK=1, IKT
      
      ZF (JI, JK, JBLK)=-TURBN%XCSHF*PPHI3 (JI, JK, JBLK)*ZKEFF (JI&
      &, JK, JBLK)*ZWORK1 (JI, JK, JBLK)/PDZZ (JI, JK, JBLK)
      ZDFDDTDZ (JI, JK, JBLK)=-TURBN%XCSHF*ZKEFF (JI, JK, JBLK)*ZWORK2 (JI, JK, JBLK)
    
    ENDDO

  ENDDO

