          ZDFDDRDZ (JI, JK, JBLK)=ZDFDDRDZ (JI, JK, JBLK)+ZWORK2 (JI, JK, JBLK)*ZWORK1 (JI, JK, JBLK)
        
        ENDDO

      ENDDO

    ENDDO

  ENDIF


  IF (OOCEAN) THEN
    
    !$ACC PARALLEL LOOP GANG &
    !$ACC&IF (LDACC) &
    !$ACC&PRIVATE (JBLK) &
    !$ACC&VECTOR_LENGTH (D%NIT) 

    

    DO JBLK = 1, KGPBLKS
      
      !$ACC LOOP VECTOR &
      !$ACC&PRIVATE (JI) 

      

