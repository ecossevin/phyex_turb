      DO JK=1, IKT
        
        ZF (JI, JK, JBLK)=ZF (JI, JK, JBLK)+ZWORK1 (JI, JK, JBLK)*PFWR (JI, JK, JBLK)
        ZDFDDTDZ (JI, JK, JBLK)=ZDFDDTDZ (JI, JK, JBLK)+ZWORK2 (JI, JK, JBLK)*PFWR (JI, JK, JBLK)
      
      ENDDO

