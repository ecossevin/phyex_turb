    CALL D_M3_WR_WTHR_O_DDRDZ_MANYBLOCKS (D, CSTURB, TURBN, Z3RDMOMENT, PREDR1, PREDTH1&
    &, PD, PBLL_O_E, PEMOIST, ZWORK2, LDACC = LDACC, KGPBLKS = KGPBLKS)
    
    !$ACC PARALLEL LOOP GANG &
    !$ACC&IF (LDACC) &
    !$ACC&PRIVATE (JBLK) &
    !$ACC&VECTOR_LENGTH (D%NIT) 

    

