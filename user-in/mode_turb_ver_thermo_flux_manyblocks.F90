  GFTH2=ANY (PFTH2 (:,:,:)/=0.)
  GFR2=ANY (PFR2 (:,:,:)/=0.).AND.GUSERV
  GFTHR=ANY (PFTHR (:,:,:)/=0.).AND.GUSERV
  GFWTH=ANY (PFWTH (:,:,:)/=0.)
  GFWR=ANY (PFWR (:,:,:)/=0.).AND.GUSERV
