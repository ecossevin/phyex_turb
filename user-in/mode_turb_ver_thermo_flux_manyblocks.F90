      !$ACC&IF (LDACC) &
      !$ACC&PRIVATE (JBLK) &
      !$ACC&VECTOR_LENGTH (D%NIT) 

      

      DO JBLK = 1, KGPBLKS
        
        !$ACC LOOP VECTOR &
        !$ACC&PRIVATE (JI, JK) 

        

        DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

          DO JK=1, IKT
            
            ZWORK2 (JI, JK, JBLK)=ZFLXZ (JI, JK, JBLK)/PDZZ (JI, JK, JBLK)
          
          ENDDO

        ENDDO

      ENDDO

      CALL DZF_PHY_MANYBLOCKS (D, ZWORK2, ZWORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)

      IF (KRRI>=1) THEN
        
        !$ACC PARALLEL LOOP GANG &
        !$ACC&IF (LDACC) &
        !$ACC&PRIVATE (JBLK) &
        !$ACC&VECTOR_LENGTH (D%NIT) 

        

        DO JBLK = 1, KGPBLKS
          
          !$ACC LOOP VECTOR &
          !$ACC&PRIVATE (JI, JK) 

          

          DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

            DO JK=1, IKT
              
              PRRS (JI, JK, 2, JBLK)=PRRS (JI, JK, 2, JBLK)-PRHODJ (JI, JK, JBLK)*PAMOIST (JI, JK, JBLK&
              &)*2.*PSRCM (JI, JK, JBLK)*ZWORK1 (JI, JK, JBLK)*(1.0-PFRAC_ICE (JI, JK, JBLK))
              PRRS (JI, JK, 4, JBLK)=PRRS (JI, JK, 4, JBLK)-PRHODJ (JI, JK, JBLK)*PAMOIST (JI, JK&
