    !$ACC&PRIVATE (JI, JK) 

    

    DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

      DO JK=1, IKT
        
        ZRWRNP (JI, JK, JBLK)=PRHODJ (JI, JK, JBLK)*(PRP (JI, JK, JBLK)-PRM (JI, JK, 1, JBLK))/PTSTEP
      
      ENDDO


      DO JK=1, IKT
        
        ZWORK1 (JI, JK, JBLK)=PRP (JI, JK, JBLK)-PRM (JI, JK, 1, JBLK)
      
      ENDDO

    ENDDO

  ENDDO

  
  
  CALL DZM_PHY_MANYBLOCKS (D, ZWORK1, ZWORK2, LDACC = LDACC, KGPBLKS = KGPBLKS)
  
  !$ACC PARALLEL LOOP GANG &
  !$ACC&IF (LDACC) &
  !$ACC&PRIVATE (JBLK) &
  !$ACC&VECTOR_LENGTH (D%NIT) 

  

  DO JBLK = 1, KGPBLKS
    
    !$ACC LOOP VECTOR &
    !$ACC&PRIVATE (JI, JK) 

    

    DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

      DO JK=1, IKT
        
        PRRS (JI, JK, 1, JBLK)=PRRS (JI, JK, 1, JBLK)+ZRWRNP (JI, JK, JBLK)
        ZFLXZ (JI, JK, JBLK)=ZF (JI, JK, JBLK)+TURBN%XIMPL*ZDFDDRDZ &
        &(JI, JK, JBLK)*ZWORK2 (JI, JK, JBLK)/PDZZ (JI, JK, JBLK)
      
      ENDDO

      
      ZFLXZ (JI, IKA, JBLK)=ZFLXZ (JI, IKB, JBLK)
    
    ENDDO

  ENDDO


  

  

  IF (OOCEAN) THEN
    
    !$ACC PARALLEL LOOP GANG &
    !$ACC&IF (LDACC) &
    !$ACC&PRIVATE (JBLK) &
    !$ACC&VECTOR_LENGTH (D%NIT) 

    

    DO JBLK = 1, KGPBLKS
      
      !$ACC LOOP VECTOR &
      !$ACC&PRIVATE (JI) 

      

      DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)
        
        ZFLXZ (JI, IKU, JBLK)=ZFLXZ (JI, IKE, JBLK)
      
      ENDDO

    ENDDO

  ENDIF


  

  

  IF (OOCEAN) THEN
    CALL MZF_PHY_MANYBLOCKS (D, ZFLXZ, ZMZF2D_WORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)
    
    !$ACC PARALLEL LOOP GANG &
    !$ACC&IF (LDACC) &
    !$ACC&PRIVATE (JBLK) &
    !$ACC&VECTOR_LENGTH (D%NIT) 

    

    DO JBLK = 1, KGPBLKS
      
      !$ACC LOOP VECTOR &
      !$ACC&PRIVATE (JI, JK) 

      

      DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

        DO JK=1, IKT
          
          ZA (JI, JK, JBLK)=-CST%XG*CST%XBETAOC*ZMZF2D_WORK1 (JI, JK, JBLK)
        
        ENDDO

      ENDDO

    ENDDO

  ELSE
    CALL MZM_PHY_MANYBLOCKS (D, PEMOIST, ZMZM2D_WORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)
    
    !$ACC PARALLEL LOOP GANG &
    !$ACC&IF (LDACC) &
    !$ACC&PRIVATE (JBLK) &
    !$ACC&VECTOR_LENGTH (D%NIT) 

    

    DO JBLK = 1, KGPBLKS
      
      !$ACC LOOP VECTOR &
      !$ACC&PRIVATE (JI, JK) 

      

      DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

        DO JK=1, IKT
          
          ZSHUGRADWK1_2D (JI, JK, JBLK)=ZMZM2D_WORK1 (JI, JK, JBLK)*ZFLXZ (JI, JK, JBLK)
        
        ENDDO

      ENDDO

