    CALL MZF_PHY_MANYBLOCKS (D, ZSHUGRADWK1_2D, ZMZF2D_WORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)
    
    !$ACC PARALLEL LOOP GANG &
    !$ACC&IF (LDACC) &
    !$ACC&PRIVATE (JBLK) &
    !$ACC&VECTOR_LENGTH (D%NIT) 

    

    DO JBLK = 1, KGPBLKS
      
      !$ACC LOOP VECTOR &
      !$ACC&PRIVATE (JI, JK) 

      

      DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

        DO JK=1, IKT
          
          ZA (JI, JK, JBLK)=PBETA (JI, JK, JBLK)*ZMZF2D_WORK1 (JI, JK, JBLK)
        
        ENDDO

        
        ZA (JI, IKB, JBLK)=PBETA (JI, IKB, JBLK)*PEMOIST (JI, IKB, JBLK&
        &)*0.5*(ZFLXZ (JI, IKB, JBLK)+ZFLXZ (JI, IKB+IKL, JBLK))

        

        DO JK=1, IKT
          
          PTP (JI, JK, JBLK)=PTP (JI, JK, JBLK)+ZA (JI, JK, JBLK)
        
        ENDDO

      ENDDO

    ENDDO

  
  
  ENDIF

  CALL MZM_PHY_MANYBLOCKS (D, PEMOIST, ZMZM2D_WORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)
  
  !$ACC PARALLEL LOOP GANG &
  !$ACC&IF (LDACC) &
  !$ACC&PRIVATE (JBLK) &
  !$ACC&VECTOR_LENGTH (D%NIT) 

  

  DO JBLK = 1, KGPBLKS
    
    !$ACC LOOP VECTOR &
    !$ACC&PRIVATE (JI, JK) 

    

    DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

      DO JK=1, IKT
        
        PWTHV (JI, JK, JBLK)=PWTHV (JI, JK, JBLK)+ZMZM2D_WORK1 (JI, JK, JBLK)*ZFLXZ (JI, JK, JBLK)
      
      ENDDO

      
      PWTHV (JI, IKB, JBLK)=PWTHV (JI, IKB, JBLK)+PEMOIST (JI, IKB, JBLK)*ZFLXZ (JI, IKB, JBLK)
    
    ENDDO

