#include "fxtran_acdc_stack.h"

IMPLICIT NONE

#ifdef MNH_COMPILER_CCE
#endif
TYPE (DIMPHYEX_T), INTENT (IN)::D
TYPE (CST_T), INTENT (IN)::CST
TYPE (CSTURB_T), INTENT (IN)::CSTURB
TYPE (TURB_T), INTENT (IN)::TURBN
INTEGER, INTENT (IN)::KSV
INTEGER, INTENT (IN)::KRR
INTEGER, INTENT (IN)::KRRI
LOGICAL, INTENT (IN)::OTURB_DIAG
LOGICAL, INTENT (IN)::OOCEAN
LOGICAL, INTENT (IN)::OHARAT
LOGICAL, INTENT (IN)::OCOMPUTE_SRC
LOGICAL, INTENT (IN)::O2D
LOGICAL, INTENT (IN)::OFLAT
CHARACTER (LEN=4), INTENT (IN)::HTURBDIM
TYPE (TFILEDATA), INTENT (INOUT)::TPFILE
REAL, INTENT (IN)::PDZY(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PDZX(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PDZZ(D%NIJT, D%NKT, KGPBLKS)
REAL, INTENT (IN)::PDYY(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PDXX(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PTHVREF(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PLOCPEXNM(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PATHETA(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PAMOIST(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PLM(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PLEPS(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PTKEM(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PTHLM(D%NIJT, D%NKT, KGPBLKS)
!REAL, INTENT (IN)::PRM(:, :, :, :) ! (D%NIJT, D%NKT, KRR)
REAL, INTENT (IN)::PRM(D%NIJT, D%NKT, KRR, KGPBLKS)
!REAL, INTENT (IN)::PSVM(:, :, :, :) ! (D%NIJT, D%NKT, KSV)
REAL, INTENT (IN)::PSVM(D%NIJT, D%NKT, KSV, KGPBLKS)
REAL, INTENT (IN)::PSRCM(MERGE (D%NIT, 0, OCOMPUTE_SRC), MERGE&
& (D%NJT, 0, OCOMPUTE_SRC), MERGE (D%NKT, 0, OCOMPUTE_SRC))
REAL, INTENT (OUT)::PREDTH1(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (OUT)::PREDR1(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (OUT)::PRED2TH3(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (OUT)::PRED2R3(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (OUT)::PRED2THR3(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (OUT)::PREDS1(:, :, :, :) ! (D%NIJT, D%NKT, KSV)
REAL, INTENT (OUT)::PRED2THS3(:, :, :, :) ! (D%NIJT, D%NKT, KSV)
REAL, INTENT (OUT)::PRED2RS3(:, :, :, :) ! (D%NIJT, D%NKT, KSV)
REAL, INTENT (OUT)::PBLL_O_E(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (OUT)::PETHETA(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (OUT)::PEMOIST(:, :, :) ! (D%NIJT, D%NKT)
INTEGER, INTENT (IN) :: KGPBLKS
LOGICAL, INTENT (IN) :: LDACC
REAL ::ZPRM(D%NIJT, D%NKT, KGPBLKS)
REAL ::ZPSVM(D%NIJT, D%NKT, KGPBLKS)
REAL::ZGYMM_PSV(D%NIJT, D%NKT,KGPBLKS)
REAL::ZGXMM_PSV(D%NIJT, D%NKT,KGPBLKS)
REAL::ZGYMM_PRM(D%NIJT, D%NKT,KGPBLKS)
REAL::ZGXMM_PRM(D%NIJT, D%NKT,KGPBLKS)
REAL::ZGYMM_PTH(D%NIJT, D%NKT,KGPBLKS)
REAL::ZGXMM_PTH(D%NIJT, D%NKT,KGPBLKS)
REAL::ZWORK4(D%NIJT, D%NKT,KGPBLKS)
REAL::ZWORK3(D%NIJT, D%NKT,KGPBLKS)
REAL::ZWORK2(D%NIJT, D%NKT,KGPBLKS)
REAL::ZWORK1(D%NIJT, D%NKT,KGPBLKS)
REAL::ZW2(D%NIJT, D%NKT,KGPBLKS)
REAL::ZW1(D%NIJT, D%NKT,KGPBLKS)
INTEGER::IKB
INTEGER::IKE
INTEGER::JK
INTEGER::JI
INTEGER::JSV
INTEGER::IKL
INTEGER::IKA
INTEGER::IKT
INTEGER::IIJE
INTEGER::IIJB
REAL::ZMINVAL
TYPE (TFIELDMETADATA)::TZFIELD
REAL (KIND=JPHOOK)::ZHOOK_HANDLE
TYPE (FXTRAN_ACDC_STACK) :: YLSTACK
INTEGER :: JBLK

!$ACC DATA &
!$ACC&CREATE (ZGXMM_PRM, ZGXMM_PSV, ZGXMM_PTH, ZGYMM_PRM, ZGYMM_PSV, ZGYMM_PTH, &
!$ACC&        ZW1, ZW2, ZWORK1, ZWORK2, ZWORK3, ZWORK4, ZPSVM, ZPRM) &
!$ACC&IF (LDACC) &
!$ACC&PRESENT (CST, CSTURB, D, PAMOIST, PATHETA, PBLL_O_E, PDXX, PDYY, PDZX, PDZY, PDZZ, &
!$ACC&         PEMOIST, PETHETA, PLEPS, PLM, PLOCPEXNM, PRED2R3, PRED2RS3, PRED2TH3, &
!$ACC&         PRED2THR3, PRED2THS3, PREDR1, PREDS1, PREDTH1, PRM, PSRCM, PSVM, PTHLM, &
!$ACC&         PTHVREF, PTKEM, TPFILE, TURBN) 
IF (LHOOK) CALL DR_HOOK ('PRANDTL_MANYBLOCKS', 0, ZHOOK_HANDLE)

IKB=D%NKTB
IKE=D%NKTE
IIJE=D%NIJE
IIJB=D%NIJB
IKT=D%NKT
IKA=D%NKA
IKL=D%NKL
CALL ETHETA_MANYBLOCKS (D, CST, KRR, KRRI, PTHLM, PRM, PLOCPEXNM, PATHETA,&
& PSRCM, OOCEAN, OCOMPUTE_SRC, ZWORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)
CALL EMOIST_MANYBLOCKS (D, CST, KRR, KRRI, PTHLM, PRM, PLOCPEXNM, PAMOIST&
&, PSRCM, OOCEAN, ZWORK2, LDACC = LDACC, KGPBLKS = KGPBLKS)
CALL MZM_PHY_MANYBLOCKS (D, ZWORK1, PETHETA, LDACC = LDACC, KGPBLKS = KGPBLKS)
CALL MZM_PHY_MANYBLOCKS (D, ZWORK2, PEMOIST, LDACC = LDACC, KGPBLKS = KGPBLKS)

!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT) 


DO JBLK = 1, KGPBLKS
  
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)
    
    PETHETA (JI, IKA, JBLK)=2.*PETHETA (JI, IKB, JBLK)-PETHETA (JI, IKB+IKL, JBLK)
    PEMOIST (JI, IKA, JBLK)=2.*PEMOIST (JI, IKB, JBLK)-PEMOIST (JI, IKB+IKL, JBLK)
  
  ENDDO

ENDDO



IF (OOCEAN) THEN
  
  !$ACC PARALLEL LOOP GANG &
  !$ACC&IF (LDACC) &
  !$ACC&PRIVATE (JBLK) &
  !$ACC&VECTOR_LENGTH (D%NIT) 

  

  DO JBLK = 1, KGPBLKS
    
    !$ACC LOOP VECTOR &
    !$ACC&PRIVATE (JI, JK) 

    

    DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

      DO JK=1, IKT
        
        ZWORK1 (JI, JK, JBLK)=CST%XG*CST%XALPHAOC*PLM (JI, JK&
        &, JBLK)*PLEPS (JI, JK, JBLK)/PTKEM (JI, JK, JBLK)
      
      ENDDO

    ENDDO

  ENDDO

ELSE
  
  !$ACC PARALLEL LOOP GANG &
  !$ACC&IF (LDACC) &
  !$ACC&PRIVATE (JBLK) &
  !$ACC&VECTOR_LENGTH (D%NIT) 

  

  DO JBLK = 1, KGPBLKS
    
    !$ACC LOOP VECTOR &
    !$ACC&PRIVATE (JI, JK) 

    

    DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

      DO JK=1, IKT
        
        ZWORK1 (JI, JK, JBLK)=CST%XG/PTHVREF (JI, JK, JBLK)*PLM (JI&
        &, JK, JBLK)*PLEPS (JI, JK, JBLK)/PTKEM (JI, JK, JBLK)
      
      ENDDO

    ENDDO

  ENDDO

ENDIF

CALL MZM_PHY_MANYBLOCKS (D, ZWORK1, PBLL_O_E, LDACC = LDACC, KGPBLKS = KGPBLKS)

CALL GZ_M_W_PHY_MANYBLOCKS (D, PTHLM, PDZZ, ZWORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)

IF (OOCEAN) THEN
  
  !$ACC PARALLEL LOOP GANG &
  !$ACC&IF (LDACC) &
  !$ACC&PRIVATE (JBLK) &
  !$ACC&VECTOR_LENGTH (D%NIT) 

  

  DO JBLK = 1, KGPBLKS
    
    !$ACC LOOP VECTOR &
    !$ACC&PRIVATE (JI, JK) 

    

    DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

      DO JK=1, IKT
        
        PREDTH1 (JI, JK, JBLK)=TURBN%XCTV*PBLL_O_E (JI, JK, JBLK)*ZWORK1 (JI, JK, JBLK)
      
      ENDDO

      PREDR1 (JI, 1:IKT, JBLK)=0.
    ENDDO

  ENDDO

  
ELSE

  IF (KRR/=0) THEN
    !$ACC PARALLEL LOOP GANG &
    !$ACC&IF (LDACC) &
    !$ACC&PRIVATE (JBLK) &
    !$ACC&VECTOR_LENGTH (D%NIT)
    DO JBLK = 1, KGPBLKS
      !$ACC LOOP VECTOR &
      !$ACC&PRIVATE (JI, JK) 
      DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)
        DO JK=1, IKT
          ZPRM(JI, JK, JBLK) =  PRM(JI, JK, 1, JBLK)  
        ENDDO
      ENDDO
    ENDDO
    CALL GZ_M_W_PHY_MANYBLOCKS (D, ZPRM, PDZZ, ZWORK2, LDACC = LDACC, KGPBLKS = KGPBLKS)
    !CALL GZ_M_W_PHY_MANYBLOCKS (D, PRM (:,:, 1,:), PDZZ, ZWORK2, LDACC = LDACC, KGPBLKS = KGPBLKS)

    !$ACC PARALLEL LOOP GANG &
    !$ACC&IF (LDACC) &
    !$ACC&PRIVATE (JBLK) &
    !$ACC&VECTOR_LENGTH (D%NIT) 

    

    DO JBLK = 1, KGPBLKS
      
      !$ACC LOOP VECTOR &
      !$ACC&PRIVATE (JI, JK) 

      

      DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

        DO JK=1, IKT
          
          PREDTH1 (JI, JK, JBLK)=TURBN%XCTV*PBLL_O_E (JI, JK, JBLK&
          &)*PETHETA (JI, JK, JBLK)*ZWORK1 (JI, JK, JBLK)
          PREDR1 (JI, JK, JBLK)=TURBN%XCTV*PBLL_O_E (JI, JK, JBLK&
          &)*PEMOIST (JI, JK, JBLK)*ZWORK2 (JI, JK, JBLK)
        
        ENDDO

      ENDDO

    ENDDO

  ELSE
    
    !$ACC PARALLEL LOOP GANG &
    !$ACC&IF (LDACC) &
    !$ACC&PRIVATE (JBLK) &
    !$ACC&VECTOR_LENGTH (D%NIT) 

    

    DO JBLK = 1, KGPBLKS
      
      !$ACC LOOP VECTOR &
      !$ACC&PRIVATE (JI, JK) 

      

      DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

        DO JK=1, IKT
          
          PREDTH1 (JI, JK, JBLK)=TURBN%XCTV*PBLL_O_E (JI, JK, JBLK)*ZWORK1 (JI, JK, JBLK)
          PREDR1 (JI, JK, JBLK)=0.
        
        ENDDO

      ENDDO

    ENDDO

  ENDIF

ENDIF

ZMINVAL=(1.-1./CSTURB%XPHI_LIM)

!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT) 


DO JBLK = 1, KGPBLKS
  
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI, JK) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

    DO JK=1, IKT
      
      ZW1 (JI, JK, JBLK)=1.
      ZW2 (JI, JK, JBLK)=1.

      IF (PREDTH1 (JI, JK, JBLK)+PREDR1 (JI, JK, JBLK)<-ZMINVAL) THEN
        ZW1 (JI, JK, JBLK)=(-ZMINVAL)/(PREDTH1 (JI, JK, JBLK)+PREDR1 (JI, JK, JBLK))
      ENDIF


      IF (PREDTH1 (JI, JK, JBLK)<-ZMINVAL) THEN
        ZW2 (JI, JK, JBLK)=(-ZMINVAL)/(PREDTH1 (JI, JK, JBLK))
      ENDIF

      ZW2 (JI, JK, JBLK)=MIN (ZW1 (JI, JK, JBLK), ZW2 (JI, JK, JBLK))
      ZW1 (JI, JK, JBLK)=1.

      IF (PREDR1 (JI, JK, JBLK)<-ZMINVAL) THEN
        ZW1 (JI, JK, JBLK)=(-ZMINVAL)/(PREDR1 (JI, JK, JBLK))
      ENDIF

      ZW1 (JI, JK, JBLK)=MIN (ZW2 (JI, JK, JBLK), ZW1 (JI, JK, JBLK))
      PBLL_O_E (JI, JK, JBLK)=PBLL_O_E (JI, JK, JBLK)*ZW1 (JI, JK, JBLK)
      PREDTH1 (JI, JK, JBLK)=PREDTH1 (JI, JK, JBLK)*ZW1 (JI, JK, JBLK)
      PREDR1 (JI, JK, JBLK)=PREDR1 (JI, JK, JBLK)*ZW1 (JI, JK, JBLK)

      IF (PREDTH1 (JI, JK, JBLK)<0.) THEN
        ZW2 (JI, JK, JBLK)=-1.
      ELSE
        ZW2 (JI, JK, JBLK)=1.
      ENDIF

      PREDTH1 (JI, JK, JBLK)=ZW2 (JI, JK, JBLK)*MAX (CST%XMNH_TINY_12&
      &, ZW2 (JI, JK, JBLK)*PREDTH1 (JI, JK, JBLK))

      IF (KRR/=0) THEN

        IF (PREDR1 (JI, JK, JBLK)<0.) THEN
          ZW2 (JI, JK, JBLK)=-1.
        ELSE
          ZW2 (JI, JK, JBLK)=1.
        ENDIF

        PREDR1 (JI, JK, JBLK)=ZW2 (JI, JK, JBLK)*MAX (CST%XMNH_TINY_12&
        &, ZW2 (JI, JK, JBLK)*PREDR1 (JI, JK, JBLK))
      ENDIF

    
    ENDDO

  ENDDO

ENDDO


DO JSV=1, KSV
    !$ACC PARALLEL LOOP GANG &
    !$ACC&IF (LDACC) &
    !$ACC&PRIVATE (JBLK) &
    !$ACC&VECTOR_LENGTH (D%NIT) 
    DO JBLK = 1, KGPBLKS
      !$ACC LOOP VECTOR &
      !$ACC&PRIVATE (JI, JK) 
      DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)
        DO JK=1, IKT
          ZPSVM(JI, JK, JBLK) =  PSVM(JI, JK, JSV, JBLK)  
        ENDDO
      ENDDO
    ENDDO
  CALL GZ_M_W_PHY_MANYBLOCKS (D, ZPSVM, PDZZ, ZWORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)
  
  !$ACC PARALLEL LOOP GANG &
  !$ACC&IF (LDACC) &
  !$ACC&PRIVATE (JBLK) &
  !$ACC&VECTOR_LENGTH (D%NIT) 

  

  DO JBLK = 1, KGPBLKS
    
    !$ACC LOOP VECTOR &
    !$ACC&PRIVATE (JI, JK) 

    

    DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

      DO JK=1, IKT
        
        PREDS1 (JI, JK, JSV, JBLK)=TURBN%XCTV*PBLL_O_E (JI, JK, JBLK)*ZWORK1 (JI, JK, JBLK)
      
      ENDDO

    ENDDO

  ENDDO

ENDDO


DO JSV=1, KSV
  
  !$ACC PARALLEL LOOP GANG &
  !$ACC&IF (LDACC) &
  !$ACC&PRIVATE (JBLK) &
  !$ACC&VECTOR_LENGTH (D%NIT) 

  

  DO JBLK = 1, KGPBLKS
    
    !$ACC LOOP VECTOR &
    !$ACC&PRIVATE (JI, JK) 

    

    DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

      DO JK=1, IKT

        

        IF (PREDS1 (JI, JK, JSV, JBLK)<0.) THEN
          ZW2 (JI, JK, JBLK)=-1.
        ELSE
          ZW2 (JI, JK, JBLK)=1.
        ENDIF

        PREDS1 (JI, JK, JSV, JBLK)=ZW2 (JI, JK, JBLK)*MAX (CST%XMNH_TINY_12&
        &, ZW2 (JI, JK, JBLK)*PREDS1 (JI, JK, JSV, JBLK))
      
      ENDDO

    ENDDO

  ENDDO

ENDDO



!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT) 


DO JBLK = 1, KGPBLKS
  
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI, JK) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

    DO JK=1, IKT
      
      PRED2TH3 (JI, JK, JBLK)=PREDTH1 (JI, JK, JBLK)**2
      PRED2R3 (JI, JK, JBLK)=PREDR1 (JI, JK, JBLK)**2
      PRED2THR3 (JI, JK, JBLK)=PREDTH1 (JI, JK, JBLK)*PREDR1 (JI, JK, JBLK)
    
    ENDDO

  ENDDO

ENDDO



DO JSV=1, KSV
  
  
  !$ACC PARALLEL LOOP GANG &
  !$ACC&IF (LDACC) &
  !$ACC&PRIVATE (JBLK) &
  !$ACC&VECTOR_LENGTH (D%NIT) 

  

  DO JBLK = 1, KGPBLKS
    
    !$ACC LOOP VECTOR &
    !$ACC&PRIVATE (JI, JK) 

    

    DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

      DO JK=1, IKT
        
        PRED2THS3 (JI, JK, JSV, JBLK)=PREDS1 (JI, JK, JSV, JBLK)*PREDTH1 (JI, JK, JBLK)

        IF (KRR/=0) THEN
          PRED2RS3 (JI, JK, JSV, JBLK)=PREDR1 (JI, JK, JBLK)*PREDS1 (JI, JK, JSV, JBLK)
        ELSE
          PRED2RS3 (JI, JK, JSV, JBLK)=0.
        ENDIF

      
      ENDDO

    ENDDO

  ENDDO

  
ENDDO



IF (LHOOK) CALL DR_HOOK ('PRANDTL_MANYBLOCKS', 1, ZHOOK_HANDLE)
!$ACC END DATA

END SUBROUTINE PRANDTL_MANYBLOCKS

SUBROUTINE SMOOTH_TURB_FUNCT_MANYBLOCKS (D, CSTURB, TURBN, PPHI3, PF_LIM, PF, LDACC, KGPBLKS)

USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD
#include "fxtran_acdc_stack.h"

IMPLICIT NONE

TYPE (CSTURB_T), INTENT (IN)::CSTURB
TYPE (TURB_T), INTENT (IN)::TURBN
TYPE (DIMPHYEX_T), INTENT (IN)::D
REAL, INTENT (IN)::PPHI3(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (IN)::PF_LIM(:, :, :) ! (D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PF(:, :, :) ! (D%NIJT, D%NKT)
INTEGER, INTENT (IN) :: KGPBLKS
LOGICAL, INTENT (IN) :: LDACC
REAL::ZCOEF(D%NIJT, D%NKT,KGPBLKS)
INTEGER::IKT
INTEGER::IIJE
INTEGER::IIJB
INTEGER::JK
INTEGER::JI
TYPE (FXTRAN_ACDC_STACK) :: YLSTACK
INTEGER :: JBLK

!$ACC DATA &
!$ACC&CREATE (ZCOEF) &
