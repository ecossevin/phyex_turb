GFTHR=.FALSE.
GFWTH=.FALSE.
GFWR=.FALSE.

IF (TURBN%CTOM/='NONE') THEN
  GFTH2=ANY (PFTH2 (:,:,:)/=0.)
  GFR2=ANY (PFR2 (:,:,:)/=0.).AND.GUSERV
  GFTHR=ANY (PFTHR (:,:,:)/=0.).AND.GUSERV
  GFWTH=ANY (PFWTH (:,:,:)/=0.)
  GFWR=ANY (PFWR (:,:,:)/=0.).AND.GUSERV
ENDIF



!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT) 


DO JBLK = 1, KGPBLKS
  
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI, JK) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

    DO JK=1, IKT
      
      ZWORK1 (JI, JK, JBLK)=PPHI3 (JI, JK, JBLK)*PDTH_DZ (JI, JK, JBLK)**2
    
    ENDDO

  ENDDO

ENDDO

CALL MZF_PHY_MANYBLOCKS (D, ZWORK1, ZWORK2, LDACC = LDACC, KGPBLKS = KGPBLKS)

!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT) 


DO JBLK = 1, KGPBLKS
  
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI, JK) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

    DO JK=1, IKT
      
      ZF (JI, JK, JBLK)=TURBN%XCTV*PLM (JI, JK, JBLK)*PLEPS (JI, JK, JBLK)*ZWORK2 (JI, JK, JBLK)
    
    ENDDO

    ZDFDDTDZ (JI,:, JBLK)=0.
  ENDDO

ENDDO




IF (GFTH2) THEN
  CALL M3_TH2_WTH2_MANYBLOCKS (D, CSTURB, TURBN, PREDTH1, PREDR1, PD&
  &, PLEPS, PSQRT_TKE, ZWORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)
  CALL D_M3_TH2_WTH2_O_DDTDZ_MANYBLOCKS (D, CSTURB, TURBN, PREDTH1, PREDR1, PD, PLEPS&
  &, PSQRT_TKE, PBLL_O_E, PETHETA, ZWORK2, LDACC = LDACC, KGPBLKS = KGPBLKS)
  
  !$ACC PARALLEL LOOP GANG &
  !$ACC&IF (LDACC) &
  !$ACC&PRIVATE (JBLK) &
  !$ACC&VECTOR_LENGTH (D%NIT) 

  

  DO JBLK = 1, KGPBLKS
    
    !$ACC LOOP VECTOR &
    !$ACC&PRIVATE (JI, JK) 

    

    DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

      DO JK=1, IKT
        
        ZF (JI, JK, JBLK)=ZF (JI, JK, JBLK)+ZWORK1 (JI, JK, JBLK)*PFTH2 (JI, JK, JBLK)
        ZDFDDTDZ (JI, JK, JBLK)=ZDFDDTDZ (JI, JK, JBLK)+ZWORK2 (JI, JK, JBLK)*PFTH2 (JI, JK, JBLK)
      
      ENDDO

    ENDDO

  ENDDO

ENDIF


IF (GFWTH) THEN
