!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT) 


DO JBLK = 1, KGPBLKS
  
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI, JK) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)
    
    ZCOEFF (JI, IKB+2*IKL, JBLK)=-PDZZ (JI, IKB+IKL, JBLK)/((PDZZ (JI, IKB&
    &+2*IKL, JBLK)+PDZZ (JI, IKB+IKL, JBLK))*PDZZ (JI, IKB+2*IKL, JBLK))
    ZCOEFF (JI, IKB+IKL, JBLK)=(PDZZ (JI, IKB+2*IKL, JBLK)+PDZZ (JI, IKB+IKL&
    &, JBLK))/(PDZZ (JI, IKB+IKL, JBLK)*PDZZ (JI, IKB+2*IKL, JBLK))
    ZCOEFF (JI, IKB, JBLK)=-(PDZZ (JI, IKB+2*IKL, JBLK)+2.*PDZZ (JI, IKB+IKL, JBLK))/(&
    &(PDZZ (JI, IKB+2*IKL, JBLK)+PDZZ (JI, IKB+IKL, JBLK))*PDZZ (JI, IKB+IKL, JBLK))

    

    DO JK=1, IKT
      
      ZWORK1 (JI, JK, JBLK)=PLM (JI, JK, JBLK)*SQRT (PTKEM (JI, JK, JBLK))
    
    ENDDO

  ENDDO

ENDDO



CALL MZM_PHY_MANYBLOCKS (D, ZWORK1, ZKEFF, LDACC = LDACC, KGPBLKS = KGPBLKS)
