!$ACC DATA &
!$ACC&CREATE (PLEPSF, PLMF, ZCOEFF, ZDFDDRDZ, ZDFDDTDZ, ZDZM2D_WORK1, ZDZM2D_WORK2, &
!$ACC&        ZDZM2D_WORK3, ZDZM2D_WORK4, ZF, ZFLXZ, ZKEFF, ZMZF2D_WORK1, ZMZF2D_WORK2, &
