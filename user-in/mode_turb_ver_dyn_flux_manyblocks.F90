  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)
    ZA (JI,:, JBLK)=XUNDEF
    PDP (JI,:, JBLK)=XUNDEF
    ZSOURCE (JI,:, JBLK)=0.
    ZFLXZ (JI,:, JBLK)=0.
  ENDDO

ENDDO




ZCMFS=CSTURB%XCMFS


!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT) 


DO JBLK = 1, KGPBLKS
  
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI, JK) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)
    
    ZDIRSINZW (JI, JBLK)=SQRT (1.-PDIRCOSZW (JI, JBLK)**2)

    

    DO JK=1, IKT
      
      ZWORK1 (JI, JK, JBLK)=PLM (JI, JK, JBLK)*SQRT (PTKEM (JI, JK, JBLK))
    
    ENDDO

  ENDDO

ENDDO



CALL MZM_PHY_MANYBLOCKS (D, ZWORK1, ZKEFF, LDACC = LDACC, KGPBLKS = KGPBLKS)


!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT) 


DO JBLK = 1, KGPBLKS
  
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)
    ZUSLOPEM (JI, JBLK)=PUSLOPEM (JI, JBLK)
    ZVSLOPEM (JI, JBLK)=PVSLOPEM (JI, JBLK)
    ZFLUXSFCU (JI, JBLK)=PSFUM (JI, JBLK)
    ZFLUXSFCV (JI, JBLK)=PSFVM (JI, JBLK)
  ENDDO

ENDDO




CALL MXM_PHY_MANYBLOCKS (D, ZKEFF, ZMXM2D_WORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)
CALL MZM_PHY_MANYBLOCKS (D, PRHODJ, ZMZM2D_WORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)
CALL MXM_PHY_MANYBLOCKS (D, ZMZM2D_WORK1, ZMXM2D_WORK2, LDACC = LDACC, KGPBLKS = KGPBLKS)
CALL MXM_PHY_MANYBLOCKS (D, PDZZ, ZMXM2D_WORK3, LDACC = LDACC, KGPBLKS = KGPBLKS)

!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT) 


DO JBLK = 1, KGPBLKS
  
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI, JK) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)

    DO JK=1, IKT
      
      ZA (JI, JK, JBLK)=-PTSTEP*ZCMFS*ZMXM2D_WORK1 (JI, JK, JBLK)*ZMXM2D_WORK2&
      & (JI, JK, JBLK)/ZMXM2D_WORK3 (JI, JK, JBLK)**2
    
    ENDDO

    
    ZCOEFFLXU (JI, JBLK)=PCDUEFF (JI, JBLK)*(PDIRCOSZW (JI, JBLK&
    &)**2-ZDIRSINZW (JI, JBLK)**2)*PCOSSLOPE (JI, JBLK)
    ZCOEFFLXV (JI, JBLK)=PCDUEFF (JI, JBLK)*PDIRCOSZW (JI, JBLK)*PSINSLOPE (JI, JBLK)
    ZCOEFS (JI, JBLK)=ZCOEFFLXU (JI, JBLK)*PCOSSLOPE (JI, JBLK)*PDIRCOSZW&
    & (JI, JBLK)+ZCOEFFLXV (JI, JBLK)*PSINSLOPE (JI, JBLK)
    
    
    ZSHUGRADWK1_1D (JI, JBLK)=ZCOEFS (JI, JBLK)/PDZZ (JI, IKB, JBLK)
  
  ENDDO

ENDDO



CALL MXM2D_PHY_MANYBLOCKS (D, ZSHUGRADWK1_1D, ZMXM1D_WORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)

!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT) 


DO JBLK = 1, KGPBLKS
  
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI, JK) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)
    
    ZCOEFS (JI, JBLK)=ZMXM1D_WORK1 (JI, JBLK)

    

    DO JK=IKTB+1, IKTE-1
      
      ZSOURCE (JI, JK, JBLK)=0.
    
    ENDDO

    
    ZSOURCE (JI, IKB, JBLK)=PTAU11M (JI, JBLK)*PCOSSLOPE (JI, JBLK)*PDIRCOSZW (JI, JBLK)&
    &*ZDIRSINZW (JI, JBLK)-PTAU12M (JI, JBLK)*PSINSLOPE (JI, JBLK)*ZDIRSINZW (JI, JBLK)-PTAU33M&
    & (JI, JBLK)*PCOSSLOPE (JI, JBLK)*ZDIRSINZW (JI, JBLK)*PDIRCOSZW (JI, JBLK)
    
    
    ZSHUGRADWK1_1D (JI, JBLK)=ZSOURCE (JI, IKB, JBLK)/PDZZ (JI, IKB, JBLK)
  
  ENDDO

ENDDO





CALL MXM2D_PHY_MANYBLOCKS (D, ZSHUGRADWK1_1D, ZMXM1D_WORK1, LDACC = LDACC, KGPBLKS = KGPBLKS)

!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT) 


DO JBLK = 1, KGPBLKS
  
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI) 

  

  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)
    
    ZSHUGRADWK1_1D (JI, JBLK)=ZCOEFFLXU (JI, JBLK)/PDZZ (JI, IKB, JBLK)*ZUSLOPEM&
    & (JI, JBLK)-ZCOEFFLXV (JI, JBLK)/PDZZ (JI, IKB, JBLK)*ZVSLOPEM (JI, JBLK)
  
  ENDDO

ENDDO

CALL MXM2D_PHY_MANYBLOCKS (D, ZSHUGRADWK1_1D, ZMXM1D_WORK2, LDACC = LDACC, KGPBLKS = KGPBLKS)
!$ACC PARALLEL LOOP GANG &
!$ACC&IF (LDACC) &
!$ACC&PRIVATE (JBLK) &
!$ACC&VECTOR_LENGTH (D%NIT)
DO JBLK = 1, KGPBLKS
  !$ACC LOOP VECTOR &
  !$ACC&PRIVATE (JI) 
  DO JI = D%NIB, MERGE (D%NIT, D%NIE, JBLK < KGPBLKS)
    ZPRHODJ(JI, JBLK) =  PRHODJ(JI, IKA, JBLK)  
  ENDDO
ENDDO
CALL MXM2D_PHY_MANYBLOCKS (D, ZPRHODJ, ZMXM1D_WORK3, LDACC = LDACC, KGPBLKS = KGPBLKS)
!$ACC PARALLEL LOOP GANG &
