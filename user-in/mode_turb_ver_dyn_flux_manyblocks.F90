!$ACC&PRESENT (CST, CSTURB, D, MFMOIST, PCDUEFF, PCOSSLOPE, PDIRCOSZW, PDP, PDXX, PDYY, &
!$ACC&         PDZX, PDZY, PDZZ, PLM, PRHODJ, PRM, PRUS, PRVS, PRWS, PSFUM, PSFVM, PSINSLOPE, &
!$ACC&         PSSUFL, PSSUFL_C, PSSVFL, PSSVFL_C, PSVM, PTAU11M, PTAU12M, PTAU33M, &
!$ACC&         PTHLM, PTKEM, PTP, PUM, PUSLOPEM, PVM, PVSLOPEM, PWM, PWU, PWV, PZZ, TLES, &
